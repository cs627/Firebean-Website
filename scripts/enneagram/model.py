def score(answers):
    """answers: {qid: [keys]}"""
    s = {i:0 for i in range(1,10)}
    for qq in Q:
        for k in answers.get(qq["id"], []):
            for o in qq["options"]:
                if o["k"] == k:
                    for t, w in o["w"].items(): s[int(t)] += w
    return s

def simulate():
    miss = []
    for t in range(1, 10):
        ans = {}
        for qq in Q:
            if qq["kind"] == "single":
                best = max(qq["options"], key=lambda o: (o["w"].get(str(t),0), -qq["options"].index(o)))
                ans[qq["id"]] = [best["k"]]
            else:
                ranked = sorted(qq["options"], key=lambda o: -o["w"].get(str(t),0))
                n = min(qq.get("max") or len(ranked), len(ranked))
                ans[qq["id"]] = [o["k"] for o in ranked[:n]]
        s = score(ans)
        win = max(s, key=lambda k: (s[k], -k))
        ok = (win == t)
        if not ok: miss.append((t, win, s[t], s[win]))
    return miss

